@pytest.mark.asyncio
async def test_workspace_manager_lifecycle(temp_git_repo: Path, tmp_path: Path) -> None:
    parent_dir = tmp_path / "worktrees"
    mgr = WorkspaceManager(parent_dir=parent_dir)

    ws = await mgr.create_worktree("job-lifecycle-1", base_ref="HEAD", repo_path=temp_git_repo)
    assert ws.workspace_path.exists()
    assert ws.active is True
    assert (ws.workspace_path / "README.md").exists()

    # Initially no changes
    changed = await mgr.get_changed_paths(ws)
    assert changed == []

    # Modify and add a file
    (ws.workspace_path / "new_file.txt").write_text("Hello from writer\n")
    (ws.workspace_path / "README.md").write_text("# Test Repo Updated\n")

    changed = await mgr.get_changed_paths(ws)
    assert sorted(changed) == ["README.md", "new_file.txt"]

    # Cleanup
    await mgr.cleanup_worktree(ws)
    assert not ws.workspace_path.exists()
    assert ws.active is False



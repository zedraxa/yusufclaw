@pytest.mark.asyncio
async def test_writer_runner_concurrency_limit_max_two(
    temp_git_repo: Path,
    tmp_path: Path,
) -> None:
    """Verify that at most 2 writer children run concurrently."""
    worktrees_parent = tmp_path / "worktrees"
    ws_mgr = WorkspaceManager(parent_dir=worktrees_parent)

    # Create a script that sleeps briefly while recording peak concurrency
    sleeper_script = tmp_path / "sleeper_cli.py"
    sleeper_script.write_text(
        f"""#!{sys.executable}
import sys
import time
from pathlib import Path

args = sys.argv[1:]
if "--version" in args:
    print("sleeper 1.0")
    sys.exit(0)

# Simulate work with a pause
time.sleep(0.3)
sys.exit(0)
""",
        encoding="utf-8",
    )
    sleeper_script.chmod(sleeper_script.stat().st_mode | stat.S_IEXEC)

    probe = CLIProtocolProbe(executable_overrides={"sleeper": str(sleeper_script)})
    runner = WriterDelegateRunner(
        durable=False,
        probe=probe,
        workspace_manager=ws_mgr,
    )

    observed_peaks: list[int] = []

    async def run_monitored(job_num: int) -> WriterResult:
        spec = WriterSpec(
            job_id=f"concurrent-{job_num}",
            cli="sleeper",
            prompt="Pause",
            test_command=[sys.executable, "-c", "import sys; sys.exit(0)"],
            workspace_parent_dir=str(worktrees_parent),
        )
        # Sample active children count
        observed_peaks.append(runner.active_children_count)
        return await runner.run(spec)

    original_cwd = os.getcwd()
    os.chdir(temp_git_repo)
    try:
        # Launch 4 concurrent tasks
        results = await asyncio.gather(
            run_monitored(1),
            run_monitored(2),
            run_monitored(3),
            run_monitored(4),
        )
    finally:
        os.chdir(original_cwd)

    for r in results:
        assert r.success is True

    # Active children count should never exceed 2
    assert max(observed_peaks) <= 2


